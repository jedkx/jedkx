// Shared helpers for the animation library (animations/). No dependencies.
import {readFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';

export const root = new URL('../', import.meta.url);
export const at = p => new URL(p, root);
export const VENDOR = 'animations/vendor/J-Portfolio/';
export const TARGETS = ['web', 'svg', 'terminal'];
export const LEVELS = ['native', 'portable', 'no'];

export const sha256 = buf => createHash('sha256').update(buf).digest('hex');
export const loadCatalog = async () => JSON.parse(await readFile(at('animations/catalog.json'), 'utf8'));
export const sourceFiles = catalog => [...new Set(catalog.animations.flatMap(a => a.source))].sort();

const mark = {native: '●', portable: '◐', no: '·'};

// animations/README.md is generated from catalog.json so the two never drift.
export function renderReadme(catalog, lock) {
  const rows = catalog.animations.map(a => {
    const files = (a.source.length ? a.source : a.local ?? []).map(f => a.source.includes(f) ? `[\`${f.split('/').pop()}\`](vendor/J-Portfolio/${f})` : `[\`${f.split('/').pop()}\`](../${f})`).join(' ');
    const kf = a.keyframes.length ? a.keyframes.map(k => `\`${k}\``).join(' ') : '—';
    return `| \`${a.id}\` | ${a.name} | ${a.kind} | ${TARGETS.map(t => mark[a.targets[t]]).join(' ')} | ${a.usedIn.join(', ')} | ${kf} | ${files} |`;
  });
  const used = id => catalog.animations.filter(a => a.usedIn.includes(id)).map(a => `\`${a.id}\``).join(', ') || '—';
  return `<!-- Generated by scripts/sync-animations.mjs from catalog.json. Edit catalog.json, not this file. -->
# jedkx animation library

Every animation of the jedkx visual identity, in one place — **used or not**. Apps (this profile,
[J-Portfolio](https://github.com/jedkx/J-Portfolio), [jedkx-cli](https://github.com/jedkx/jedkx-cli), …)
pick from here instead of re-inventing motion.

- **Code source of truth:** \`${catalog.source.repo}\` @ \`${lock.commit.slice(0, 12)}\` (${lock.syncedAt.slice(0, 10)}). Mirrored verbatim into [\`vendor/J-Portfolio\`](vendor/J-Portfolio); hashes in [\`lock.json\`](lock.json).
- **Registry for tools and agents:** [\`catalog.json\`](catalog.json) — id, technique, files, keyframes, where it can run.
- **Completeness is checked:** the sync fails if J-Portfolio gains a \`@keyframes\` or an animated module that is not catalogued.

## Where it can run

\`web · svg · terminal\` — ● native (runs as-is) · ◐ portable (frames/timings are enough to re-implement) · · needs browser input/JS.
GitHub READMEs only render SVG with CSS/SMIL (no JavaScript), so only ● / ◐ in the **svg** column can appear in a README.

| id | animation | technique | web svg term | used in | keyframes | files |
|---|---|---|---|---|---|---|
${rows.join('\n')}

## In use

- **profile README:** ${used('profile-readme')}
- **J-Portfolio:** ${used('J-Portfolio')}
- **jedkx-cli:** ${used('jedkx-cli')}

## Taking an animation into an app

1. Pick an \`id\` above; read its files under \`vendor/J-Portfolio\` (exact timings, frames, easing).
2. Port it — keep authored durations and the palette (\`#020202\` void, \`#f5f5f5\` text, \`#ff3333\` accent).
3. Add the app to that entry's \`usedIn\` in \`catalog.json\`, then \`node scripts/sync-animations.mjs <J-Portfolio path>\`.

## Updating

\`\`\`sh
node scripts/sync-animations.mjs ../J-Portfolio   # copy, hash, completeness check, regenerate this file
node scripts/check-animations.mjs                 # offline: files, hashes, catalog, this file up to date
\`\`\`

Edit animations in J-Portfolio, never in \`vendor/\`. React Bits components keep their own license
([\`LICENSE.md\`](vendor/J-Portfolio/src/components/react-bits/LICENSE.md)).
`;
}

